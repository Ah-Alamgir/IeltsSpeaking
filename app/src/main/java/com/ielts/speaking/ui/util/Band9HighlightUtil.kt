    fun highlightBand9(
        text: String,
        vocabularies: List<Band9Vocabulary> = emptyList()
    ): AnnotatedString {
        if (text.isEmpty()) return AnnotatedString("")

        val allTerms = (baseBand9Terms + vocabularies.map { it.word })
            .filter { it.isNotBlank() }
            .distinct()
            .sortedByDescending { it.length }

        val escapedRegex = allTerms.joinToString("|") { Pattern.quote(it) }
        val pattern = Pattern.compile("(?i)\\b($escapedRegex)\\b")
        val matcher = pattern.matcher(text)

        val highlightStyle = SpanStyle(
            color = Color(0xFF047857),           // Deep rich emerald green
            background = Color(0x3310B981),      // Soft green background pill
            fontWeight = FontWeight.Bold
        )

        val builder = AnnotatedString.Builder(text)
        while (matcher.find()) {
            builder.addStyle(
                style = highlightStyle,
                start = matcher.start(),
                end = matcher.end()
            )
        }
        return builder.toAnnotatedString()
    }
